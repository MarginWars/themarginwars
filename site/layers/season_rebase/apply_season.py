"""Season 1 rebase layer (13 Nov 2026). Idempotent, in place on site_calm and review_deploy/functions.
Launch day one is Mon 16 Nov 2026, 9:00 AM PT. Config: season.json (this folder). See README.md.
 - Arcade and every game page carry a 'Season 1 starts Monday, Nov 16' lock (template + /assets/season.js + CSS),
   enforced server side by functions/_middleware.js (generated here) and client side by season.js.
 - Episodes 1-9 and Tracewire are un-parked; each episode opens on its own date (data-open, server + client).
 - Episode countdowns, Tracewire board dates, the Arcade list and game sitemap lastmod are re-dated."""
import json, re, shutil, pathlib, datetime
from zoneinfo import ZoneInfo
H = pathlib.Path(__file__).resolve().parent
ROOT = pathlib.Path("@MW_ROOT@/site_calm"); FN = pathlib.Path("@MW_ROOT@/review_deploy/functions")
C = json.loads((H / "season.json").read_text())
PT = ZoneInfo("America/Los_Angeles")
EP = {int(k): v for k, v in C["episodes"].items()}
REMAP = {C["old_episodes"][k]: C["episodes"][k] for k in C["episodes"]}
assert not set(REMAP) & set(REMAP.values()), "old and new dates overlap: the remap would not be idempotent"
def pt(iso): return datetime.datetime.fromisoformat(iso.replace("Z", "+00:00")).astimezone(PT)
def label(iso): d = pt(iso); return d.strftime("%a, %b ") + str(d.day)
def rd(p): return p.read_text()
def wr(p, s, o):
    if s != o: p.write_text(s); return 1
    return 0
n = 0
# ---------- assets: season.js (client lock) + season.css ----------
CFG = {"launch": C["launch"], "force": C["force"]}
JS = ("/* Season 1 lock, client side. Generated by site/layers/season_rebase from season.json: edit there. */\n"
"(function(){var S=" + json.dumps(CFG, separators=(",", ":")) + ",d=document,h=d.documentElement,L=Date.parse(S.launch),\n"
"PV=/(^|[?&])preview=1(&|$)/.test(location.search)&&/" + C["preview_hosts"].replace("/", "\\/") + "/.test(location.hostname),\n"
"srv=h.getAttribute('data-s1'),"
"locked=srv?srv==='locked':(PV?false:S.force==='locked'?true:S.force==='open'?false:Date.now()<L);\n"
"if(locked)h.classList.add('s1-on');\n"
"function fmt(s){return Math.floor(s/86400)+'d '+Math.floor(s%86400/3600)+'h '+Math.floor(s%3600/60)+'m'}\n"
"function ready(){var m=d.querySelector('main'),t=d.getElementById('s1-lock');\n"
" if(locked){if(t&&m){[].slice.call(m.children).forEach(function(c){if(c!==t)m.removeChild(c)});m.insertBefore(t.content.cloneNode(true),t);m.removeChild(t)}\n"
"  var cd=d.querySelector('[data-s1-cd]');if(cd&&S.force!=='locked')(function tick(){var s=(L-Date.now())/1000;if(s<=0){cd.textContent='Live now';setTimeout(function(){location.reload()},15000);return}cd.textContent=fmt(s);setTimeout(tick,30000)})();return}\n"
" if(t)t.parentNode.removeChild(t);\n"
" [].forEach.call(d.querySelectorAll('[data-s1-open]'),function(e){if((PV||Date.now()>=Date.parse(e.getAttribute('data-s1-open')))&&!/^Cleared/.test(e.textContent))e.textContent='Open'})}\n"
"if(d.readyState==='loading')d.addEventListener('DOMContentLoaded',ready);else ready()})();\n")
p = ROOT / "assets/season.js"; n += wr(p, JS, rd(p) if p.exists() else "")
p = ROOT / "assets/season.css"; n += wr(p, rd(H / "season.css"), rd(p) if p.exists() else "")
# ---------- functions/_middleware.js (server lock) ----------
SCFG = {"launch": C["launch"], "force": C["force"], "gated": C["gated"]}
MW = ("// Season 1 lock, server side. Generated by site/layers/season_rebase/apply_season.py from season.json: edit there.\n"
"// Before launch (or with force \"locked\") every gated game page is served as the lock panel only, uncached, noindex.\n"
"// After launch, an episode whose data-open time is still ahead is served without its game. ?preview=1 skips the gates\n"
"// on non-production hosts only (the dev project, its preview branches, review, localhost).\n"
"const S = " + json.dumps(SCFG) + ";\n"
"const GATED = new Set(S.gated);\n"
"const PREVIEW_HOST = /" + C["preview_hosts"].replace("/", "\\/") + "/;\n"
"const PT = new Intl.DateTimeFormat(\"en-US\", { timeZone: \"America/Los_Angeles\", weekday: \"short\", month: \"short\", day: \"numeric\" });\n"
"function seasonLocked(now, preview) {\n"
"  if (preview) return false;\n"
"  if (S.force === \"locked\") return true;\n"
"  if (S.force === \"open\") return false;\n"
"  return now < Date.parse(S.launch);\n"
"}\n"
"function epLock(iso) {\n"
"  return '<p class=\"lock\">\\u{1F512} This episode opens in <b data-drop=\"' + iso + '\">' + PT.format(new Date(iso)) + \", 9:00 AM PT</b>. Play the <a href=\\\"daily.html\\\">Daily</a> while you wait.</p>\";\n"
"}\n"
"export async function onRequest(ctx) {\n"
"  const url = new URL(ctx.request.url);\n"
"  const name = url.pathname.replace(/^\\/+|\\/+$/g, \"\").replace(/\\.html$/, \"\");\n"
"  if (!GATED.has(name) || ![\"GET\", \"HEAD\"].includes(ctx.request.method)) return ctx.next();\n"
"  const req = new Request(ctx.request);\n"
"  req.headers.delete(\"if-none-match\");\n"
"  req.headers.delete(\"if-modified-since\");\n"
"  const res = await ctx.next(req);\n"
"  if (res.status !== 200 || !(res.headers.get(\"content-type\") || \"\").includes(\"text/html\")) return res;\n"
"  const now = Date.now();\n"
"  const preview = url.searchParams.get(\"preview\") === \"1\" && PREVIEW_HOST.test(url.hostname);\n"
"  const locked = seasonLocked(now, preview);\n"
"  const rw = new HTMLRewriter().on(\"html\", {\n"
"    element(e) {\n"
"      e.setAttribute(\"data-s1\", locked ? \"locked\" : preview ? \"preview\" : \"open\");\n"
"      if (locked) e.setAttribute(\"class\", ((e.getAttribute(\"class\") || \"\") + \" s1-on\").trim());\n"
"    },\n"
"  });\n"
"  if (locked) {\n"
"    rw.on(\"main > *:not(#s1-lock)\", { element(e) { e.remove(); } })\n"
"      .on(\"template#s1-lock\", { element(e) { e.removeAndKeepContent(); } });\n"
"  } else {\n"
"    rw.on(\"template#s1-lock\", { element(e) { e.remove(); } })\n"
"      .on('section[data-game=\"ep\"][data-open]', {\n"
"        element(e) {\n"
"          const t = e.getAttribute(\"data-open\");\n"
"          if (!preview && now < Date.parse(t)) { e.removeAttribute(\"data-game\"); e.setInnerContent(epLock(t), { html: true }); }\n"
"        },\n"
"      })\n"
"      .on(\"[data-s1-open]\", {\n"
"        element(e) { if (preview || now >= Date.parse(e.getAttribute(\"data-s1-open\"))) e.setInnerContent(\"Open\"); },\n"
"      });\n"
"  }\n"
"  const out = rw.transform(res);\n"
"  const h = new Headers(out.headers);\n"
"  h.delete(\"etag\");\n"
"  h.delete(\"last-modified\");\n"
"  h.set(\"cache-control\", \"no-store\");\n"
"  if (locked) h.set(\"x-robots-tag\", \"noindex\");\n"
"  return new Response(out.body, { status: out.status, headers: h });\n"
"}\n")
p = FN / "_middleware.js"; n += wr(p, MW, rd(p) if p.exists() else "")
# ---------- Tracewire boards: consecutive dates from boards_start ----------
p = ROOT / "assets/tracewire_boards.js"; s = o = rd(p)
B = json.loads(s[s.index("["):s.rindex("]") + 1])
if B[0]["date"] != C["boards_start"]:
    # Old weeks ran Tue..Mon per episode (size 5,6,6,7,7,8 Sun,5). New weeks run Mon..Sun, so each full week's
    # Monday board moves to Tuesday: sizes stay 5,5,6,6,7,7,8 and every "Sunday:" board still lands on a Sunday.
    weeks = {}
    for b in B: weeks.setdefault(b["ep"], []).append(b)
    order = []
    for e in sorted(weeks):
        w = weeks[e]; order += ([w[0], w[6]] + w[1:6]) if len(w) == 7 else w
    d0 = datetime.date.fromisoformat(C["boards_start"])
    for i, b in enumerate(order):
        d = d0 + datetime.timedelta(days=i); b["no"] = i + 1; b["date"] = d.isoformat(); b["day"] = d.strftime("%a")
    for b in order:
        assert not b["title"].startswith("Sunday") or b["day"] == "Sun", b
    s = "window.RT_BOARDS=" + json.dumps(order, separators=(",", ":"), ensure_ascii=True) + ";\n"
n += wr(p, s, o)
# ---------- game pages ----------
GAME = {
 2: dict(title="Close Quarters", rank="Line Sergeant", need="5", leak="1", qs="sc02,ic08,ic10"),
 3: dict(title="The FX Front", rank="Flank Captain", need="7", leak="1", qs="fx01,fx02,fx10,fx12,rl24,fx08"),
 4: dict(time="20", title="Forced March", rank="Runner", need="4", qs="rl09,rl06,rl32,rl33,rl35"),
 5: dict(deal2="1", title="The Loins", rank="Reserve Commander", need="4", qs="mp04,mp15,mp18,mp19"),
 6: dict(leak="1", title="Chest and Horns", rank="Field General", need="7", qs="ic01,ic05,sc05,fx03,fx16,dp01"),
 7: dict(title="The Agent Frontier", rank="Scout", need="5", qs="ag06,ag08,ag12,ag19,ag22,ag23,ag25"),
 8: dict(title="New Currency", rank="Quartermaster", need="5", qs="st08,st64,st51,st20,st55,st37,st43"),
 9: dict(time="20", title="The Council", rank="Margin Marshal", need="7", qs="rg02,rg27,rg42,rg53,rg72,rg56,rg67,rg17,rg40,rg69"),
}
PARK = '<section aria-label="Coming soon" class="gm wk-soon-panel"><p class="wk-soon-k">Coming soon</p></section>'
def section(attrs):
    return "<section " + " ".join(f'{k}="{v}"' for k, v in sorted(attrs.items())) + "></section>"
OLDPV = r"/^(review\.themarginwars\.pages\.dev|localhost|127\.0\.0\.1)$/"
NEWPV = "/" + C["preview_hosts"].replace("/", "\\/") + "/"
IDX = "var idx=0;for(var i=0;i<B.length;i++)if(B[i].date<=today)idx=i;"
GAP = ("if(!PREV&&today>B[B.length-1].date){root.innerHTML='<div class=\"rt-lock\"><p class=\"rt-k\">Between boards</p>"
       "<h2>The next board is coming</h2><p>New Tracewire boards are on the way. Play the <a href=\"daily.html\">Daily</a> while you wait.</p></div>';return}")
for js in ("games.js", "tracewire.js"):
    p = ROOT / "assets" / js; s = o = rd(p); s = s.replace(OLDPV, NEWPV)
    if js == "tracewire.js" and GAP not in s:
        assert s.count(IDX) == 1, "tracewire idx line not found"; s = s.replace(IDX, IDX + GAP)
    n += wr(p, s, o)
LAUNCH = C["launch"]
LOCK = ('<template id="s1-lock"><div class="s1-lock"><section class="ihero"><h1><span>Season 1</span><span>starts Monday, Nov 16</span></h1>'
        '<p class="lede">Episode 1 and the first Tracewire board go live at 9:00 AM PT. New episodes follow on Mondays.</p></section>'
        '<div class="wrap"><section class="beat"><p class="eyebrow">Opens in</p><p class="cd" data-s1-cd="">' + label(LAUNCH) + ', 9:00 AM PT</p>'
        '<p>Until then, read the <a class="nm-inline nm-intext" href="writing.html">Writing</a> or meet the team on '
        '<a class="nm-inline nm-intext" href="about.html">About</a>.</p></section></div></div></template>')
HEADTAG = '<link href="/assets/season.css" rel="stylesheet"/><script src="/assets/season.js"></script>'
for g in C["gated"]:
    p = ROOT / f"{g}.html"; s = o = rd(p)
    s = s.replace(HEADTAG, "").replace("</head>", HEADTAG + "</head>", 1)
    s = re.sub(r'<template id="s1-lock">.*?</template>', "", s, flags=re.S)
    s = re.sub(r'(<main id="main" tabindex="-1">)', lambda m: m.group(1) + LOCK, s, count=1)
    s = re.sub(r'data-(drop|open)="([^"]+)"', lambda m: f'data-{m.group(1)}="{REMAP.get(m.group(2), m.group(2))}"', s)
    m = re.fullmatch(r"ep(\d)", g)
    if m:
        k = int(m.group(1))
        if k in GAME and PARK in s:
            a = {"class": "gm", "data-game": "ep", "data-ep": str(k)}; a.update({"data-" + x: v for x, v in GAME[k].items()})
            s = s.replace(PARK, section(a), 1)
        def fix(mm):
            a = dict(re.findall(r'([\w-]+)="([^"]*)"', mm.group(0))); a["data-open"] = EP[int(a["data-ep"])]; return section(a)
        s = re.sub(r'<section class="gm"[^>]*data-game="ep"[^>]*></section>', fix, s)
        if k == 2 and '<p class="eyebrow">Opens in</p>' not in s:
            s = s.replace('<section class="beat">', '<section class="beat"><p class="eyebrow">Opens in</p><p class="cd" data-drop="' + EP[2] + '">soon</p>', 1)
        if k == 1:
            s = s.replace('<span aria-disabled="true" class="btn wk-off">Episode 2: Close Quarters · Coming soon</span>', '<a class="btn" href="ep2.html">Episode 2: Close Quarters</a>')
    if g == "tracewire" and PARK in s:
        s = s.replace(PARK, '<section aria-label="Tracewire puzzle" class="gm rt" data-game="tracewire"></section>', 1)
    if g == "arcade":
        s = re.sub(r'<div aria-disabled="true" class="rt-hero wk-off">(<div>.*?)<span class="go">[^<]*</span></div>(<div aria-hidden="true" class="rt-mini">.*?</div>)</div>',
                   lambda mm: '<a class="rt-hero" href="tracewire.html">' + mm.group(1) + "<span class=\"go\">Play today's board</span></div>" + mm.group(2) + "</a>", s, count=1, flags=re.S)
        def li(mm):
            k = int(mm.group(1)); return (f'<li><a class="nm-inline" href="ep{k}.html"><span class="wn">0{k}</span>{mm.group(2)}'
                                          f'<span class="es" data-epst="{k}" data-s1-open="{EP[k]}">{label(EP[k])}</span></a></li>')
        s = re.sub(r'<li class="wk-soon"><span aria-disabled="true" class="wk-off"><span class="wn">0(\d)</span>(.*?)<span class="es">[^<]*</span></span></li>', li, s, flags=re.S)
        s = s.replace('<span class="es" data-epst="1">Open</span>', f'<span class="es" data-epst="1" data-s1-open="{EP[1]}">Open</span>')
        assert 'wk-off' not in s and s.count("data-s1-open=") == 9 and 'href="tracewire.html"' in s, "arcade rebase incomplete"
    assert s.count('id="s1-lock"') == 1 and "/assets/season.js" in s, g
    n += wr(p, s, o)
# ---------- sitemap lastmod for the re-dated game pages ----------
p = ROOT / "sitemap.xml"; s = o = rd(p)
for g in C["gated"]:
    s = re.sub(r"(<loc>https://themarginwars\.com/" + g + r"</loc><lastmod>)[^<]+", lambda m: m.group(1) + C["sitemap_lastmod"], s)
n += wr(p, s, o)
for g in C["gated"]:
    t = rd(ROOT / f"{g}.html")
    old = [x for x in C["old_episodes"].values() if x in t and x not in C["episodes"].values()]
    assert not old and "wk-soon-panel" not in t, (g, old)
print(f"SEASON: launch {C['launch']} force={C['force']}, {len(C['gated'])} gated pages, {n} files changed")
