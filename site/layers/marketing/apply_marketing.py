"""Build layer (in place on site_calm, idempotent): first-party measurement script, attribution on the assistant
escalation form, and registry-minted UTM tags on every outbound LinkedIn/Substack link."""
import pathlib, re, shutil, sys, urllib.parse
M = pathlib.Path(__file__).parent; sys.path.insert(0, str(M)); import mint_link as ml
ROOT = pathlib.Path("@MW_ROOT@/site_calm")
shutil.copyfile(M / "mk.js", ROOT / "assets/mk.js")
TAG = '<script defer="" src="/assets/mk.js"></script>'
rows = ml.load(); seen = set()
OUT = re.compile(r'href="(https://(?:www\.)?(?:[a-z0-9-]+\.)?(?:substack\.com|linkedin\.com)[^"]*)"')
def slug(rel): return re.sub(r"[^a-z0-9]+", "-", rel.removesuffix(".html").removesuffix("/index").lower()).strip("-") or "home"
n_links = 0
for p in sorted(ROOT.rglob("*.html")):
    rel = p.relative_to(ROOT).as_posix(); t = p.read_text()
    t = t.replace(TAG, ""); t = t.replace("</body>", TAG + "</body>", 1)
    t = t.replace("page:location.href,attribution:window.TMW_ATTR?TMW_ATTR():null})", "page:location.href})")
    t = t.replace("page:location.href})", "page:location.href,attribution:window.TMW_ATTR?TMW_ATTR():null})")
    fstart = t.find("<footer")
    def sub(m):
        global n_links
        raw = m.group(1).replace("&amp;", "&"); u = urllib.parse.urlsplit(raw)
        q = [(k, v) for k, v in urllib.parse.parse_qsl(u.query) if not k.startswith("utm_")]
        dest = urllib.parse.urlunsplit((u.scheme, u.netloc, u.path or "/", urllib.parse.urlencode(q), u.fragment))
        slot = "footer" if fstart != -1 and m.start() > fstart else "body"
        kind = "substack" if "substack.com" in u.netloc else "linkedin"
        rid = f"site-{slug(rel)}-{slot}-{kind}"
        if (u.path or "/") != "/": rid += "-" + re.sub(r"[^a-z0-9]+", "-", u.path.lower()).strip("-")[:40]
        url = ml.mint(dest, "themarginwars.com", "website", "always-on", f"{slug(rel)}-{slot}", id=rid, notes="site outbound link (generated by apply_marketing.py)", rows=rows, write=False)
        seen.add(rid); n_links += 1
        return 'href="' + url.replace("&", "&amp;") + '"'
    t = OUT.sub(sub, t)
    p.write_text(t)

# Visitor share buttons: the shared page URL carries the registry's share tags so LinkedIn-referred visits attribute.
SHARE_Q = "utm_source=linkedin&utm_medium=social&utm_campaign=visitor-share&utm_content="
for f, old, new in [("assets/games.js", "encodeURIComponent(base()+path)", "encodeURIComponent(base()+path+(path.indexOf('?')<0?'?':'&')+'" + SHARE_Q + "'+path.replace(/[^a-z0-9]+/gi,'-'))"),
                    ("assets/tracewire.js", "encodeURIComponent(base()+'tracewire.html')", "encodeURIComponent(base()+'tracewire.html?" + SHARE_Q + "tracewire')")]:
    fp = ROOT / f; s = fp.read_text()
    if new not in s: assert old in s, (f, "share pattern missing"); s = s.replace(old, new, 1); fp.write_text(s)
for g in ("arcade-games", "tracewire"):
    ml.mint("https://themarginwars.com/" + ("arcade.html" if g == "arcade-games" else "tracewire.html"), "linkedin", "social", "visitor-share", g, id=f"share-linkedin-{g}", notes="LinkedIn share button; utm_content is the shared page path at runtime" if g == "arcade-games" else "LinkedIn share button on TraceWire", rows=rows, write=False)
    seen.add(f"share-linkedin-{g}")
# Retire generated site rows whose link no longer exists; keep every hand-minted campaign row.
rows[:] = [r for r in rows if not r["id"].startswith(("site-", "share-")) or r["id"] in seen]
ml.save(rows)
print(f"MARKETING: mk.js on all pages; {n_links} outbound links tagged from registry ({len(seen)} site rows, {len(rows)} total)")
